#!/usr/bin/env python3
"""Regenerate HTML's named references from the committed WHATWG snapshot.

Pass --refresh to replace the snapshot from https://html.spec.whatwg.org/entities.json.
Normal regeneration is offline and deterministic.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "wireform-html/data/entities.json"
OUTPUT = ROOT / "wireform-html/src/HTML/Entities/Generated.hs"
URL = "https://html.spec.whatwg.org/entities.json"


def literal(value: str) -> str:
    pieces = []
    for char in value:
        code = ord(char)
        if char in ('"', '\\'):
            pieces.append('\\' + char)
        elif 32 <= code < 127:
            pieces.append(char)
        else:
            # The empty escape terminates a hex escape before an ASCII hex digit.
            pieces.append(f'\\x{code:X}\\&')
    return '"' + ''.join(pieces) + '"'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true')
    args = parser.parse_args()
    if args.refresh:
        SOURCE.parent.mkdir(parents=True, exist_ok=True)
        with urlopen(URL, timeout=30) as response:
            SOURCE.write_bytes(response.read())
    raw = SOURCE.read_bytes()
    entries = sorted(json.loads(raw).items())
    lines = [
        '-- Generated by scripts/regen-html-entities.py; do not edit.',
        '-- Source: ' + URL,
        '-- SHA256: ' + hashlib.sha256(raw).hexdigest(),
        'module HTML.Entities.Generated (entries) where',
        '',
        'entries :: [(String, String)]',
        'entries =',
    ]
    for index, (name, value) in enumerate(entries):
        if not name.startswith('&'):
            raise ValueError('Invalid reference name: ' + name)
        prefix = '  [ ' if index == 0 else '  , '
        lines.append(prefix + '(' + literal(name[1:]) + ', ' + literal(value['characters']) + ')')
    lines.extend(['  ]', ''])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('\n'.join(lines))
    print(f'Generated {len(entries)} references in {OUTPUT}')


if __name__ == '__main__':
    main()
