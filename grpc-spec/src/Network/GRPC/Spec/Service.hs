{- | Transport-agnostic service /implementations/.

This module is the shared vocabulary for implementing a Protobuf service
once and serving it over any transport that understands the
@'Protobuf' serv meth@ RPC tags — gRPC (@wireform-grpc@) and Connect
(@wireform-connect@) today.

== Defining a service implementation

Given service tags generated by @loadProtoServices@ (which also emits the
'ServiceMethods' instance), implement each method with 'method' and tie
the bundle together with 'service':

@
eliza :: MonadIO m => Service ElizaService m
eliza =
  service
    (  method \@Say       (\\req -> ...)
    :& method \@Introduce (\\req send -> ...)
    :& method \@Aggregate (\\recv -> ...)
    :& method \@Converse  (\\recv send -> ...)
    :& Done
    )
@

The registration is:

* __Order-insensitive__: 'service' reorders the handlers to match the
  @.proto@ declaration order ('ServiceMethods'); list them however you like.

* __Complete__: forgetting a method, listing one twice, or listing a
  method of a different service is a /compile-time/ error naming the
  offending method. A method you deliberately do not support is declared
  with 'methodUnimplemented', so the gap is visible in the source.

* __Streaming-kind-directed__: 'method' infers the handler shape from the
  RPC's 'RpcStreamingType'; there is one registration function, not four.
  The shapes are given by 'HandlerOf'.

* __Transport-neutral__: the same 'Service' value can be served over gRPC
  ('Network.GRPC.Server.Service.fromService' in @wireform-grpc@) and
  Connect (@connectHandlers@ in @wireform-connect@).

== Handler shapes

Per streaming kind ('HandlerOf'):

@
NonStreaming    : Input rpc -> m (Output rpc)
ClientStreaming : m (Maybe (Input rpc)) -> m (Output rpc)
ServerStreaming : Input rpc -> (Output rpc -> m ()) -> m ()
BiDiStreaming   : m (Maybe (Input rpc)) -> (Output rpc -> m ()) -> m ()
@

A @recv@ action returns 'Nothing' at end-of-stream; a @send@ continuation
may be called once per response message. Returning from the handler ends
the response stream — no explicit end-of-stream marker is needed.
-}
module Network.GRPC.Spec.Service (
  -- * Method list of a service
  ServiceMethods,

  -- * Handler shapes
  HandlerOf,

  -- * Single-method implementations
  MethodOf (..),
  method,
  methodUnimplemented,

  -- * Bundling
  Handlers (..),
  Service (..),
  service,

  -- * Completeness checking (exported for the benefit of type signatures)
  CompleteService (..),
  PluckMethod (..),

  -- * Adapter support
  unimplementedMessage,
) where

