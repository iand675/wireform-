/* Refresh the checked-in data vectors using liblzo2, never the tested codec.
 * Example: cc $(pkg-config --cflags lzo2) generate-reference.c \
 *   $(pkg-config --libs lzo2) -o generate-reference
 * ./generate-reference > reference_vectors.h
 * This optional generator is not a test dependency and is not distributed
 * with the Haskell package. The output contains compressed test data only.
 */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <lzo/lzo1x.h>
struct input {size_t size;unsigned kind;uint32_t seed;};
int main(void){
 if(lzo_init()!=LZO_E_OK)return 1;
 const struct input inputs[]={{0,0,0},{1,3,123},{17,1,0},{258,1,0},{1024,0,0},{4096,2,0},{2048,3,7123},{65537,0,0},{32769,2,0}};
 void *work=malloc(LZO1X_1_MEM_COMPRESS);if(!work)return 1;
 puts("/* Generated by generate-reference.c with liblzo2 2.10. Do not edit. */");
 for(size_t j=0;j<sizeof(inputs)/sizeof(inputs[0]);j++){
  const struct input *r=&inputs[j];uint8_t *plain=malloc(r->size?r->size:1),*packed=malloc(r->size+r->size/16+67);if(!plain||!packed)return 1;
  uint32_t seed=r->seed;for(size_t i=0;i<r->size;i++){seed=seed*UINT32_C(1664525)+UINT32_C(1013904223);plain[i]=r->kind==0?0:r->kind==1?(uint8_t)i:r->kind==2?(uint8_t)(i%7):(uint8_t)(seed>>24);}
  lzo_uint written=0;if(lzo1x_1_compress(plain,r->size,packed,&written,work)!=LZO_E_OK)return 1;
  printf("static const uint8_t ref_data_%zu[]={",j);for(size_t i=0;i<written;i++)printf("%s%u",i?",":"",packed[i]);puts("};");free(plain);free(packed);
 }
 puts("static const struct ref_vector ref_vectors[]={");
 for(size_t j=0;j<sizeof(inputs)/sizeof(inputs[0]);j++)printf("{%zu,%u,%u,sizeof(ref_data_%zu),ref_data_%zu},\n",inputs[j].size,inputs[j].kind,inputs[j].seed,j,j);
 puts("};");free(work);return 0;
}
